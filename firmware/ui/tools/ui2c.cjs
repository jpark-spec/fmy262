/* the expression after "const NAME = " (or ", NAME = "), up to its end at depth 0 */
function expr(name) {
  const m = new RegExp('(?:const |, )' + name.replace(/[$]/g, '\\$') + ' = ').exec(T);
  if (!m) throw new Error('no ' + name);
  let i = m.index + m[0].length, d = 0, q = null;
  const s0 = i;
  for (; i < T.length; i++) {
    const c = T[i];
    if (q) { if (c === '\\') i++; else if (c === q) q = null; continue; }
    if (c === "'" || c === '"' || c === '`') q = c;
    else if ('([{'.includes(c)) d++;
    else if (')]}'.includes(c)) d--;
    else if (d === 0 && (c === ';' || c === ',' || c === '\n')) break;
  }
  return T.slice(s0, i);
}

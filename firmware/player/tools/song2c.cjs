/* songs as C data for firmware/player: node tools/song2c.cjs [FILE.a2m ...] > songs.h
 * The demo song (web/demo.js) first, then each A2M given (web/export.js importA2M). Patterns keep only the cells
 * that hold something, row by row: ROW[p][r] .. ROW[p][r + 1] index the cells of row r, each with its track. */
const fs = require('fs'), path = require('path');
const WEB = path.join(__dirname, '../../../web');
eval(['demo.js', 'export.js'].map(f => fs.readFileSync(path.join(WEB, f), 'utf8')).join('\n') + ';global.demoSong=demoSong;global.importA2M=importA2M;');

const songs = [{ name: 'DEMO', song: demoSong() }];
for (const f of process.argv.slice(2)) songs.push({ name: path.basename(f, '.a2m').toUpperCase().slice(0, 11), song: importA2M(new Uint8Array(fs.readFileSync(f))).song });

const o = [];
o.push('/* generated by tools/song2c.cjs: do not edit */');
const op = p => `{${['am', 'vib', 'egt', 'ksr', 'mult', 'ksl', 'tl', 'ar', 'dr', 'sl', 'rr', 'ws'].map(k => p[k] | 0).join(', ')}}`;
let ncells = 0;
songs.forEach(({ song: s }, n) => {
  const P = `S${n}_`;
  s.inst.forEach((i, k) => {
    const M = i.fmm; if (!M || !M.len) return;
    o.push(`static const EngFmStep ${P}FS${k}[${M.len}] = {${M.steps.slice(0, M.len).map(st => `{{${st.d.join(', ')}}, ${st.fs}, ${st.pan}, ${st.dur}}`).join(',\n    ')}};`);
    o.push(`static const EngFmm ${P}FM${k} = {${M.len}, ${M.lb}, ${M.ll}, ${M.ko}, {${M.dis.map(d => d ? 1 : 0).join(', ')}}, ${P}FS${k}};`);
  });
  o.push(`static const EngIns ${P}INST[${s.inst.length}] = {`);
  s.inst.forEach((i, k) => o.push(`    {{${op(i.op[0])}, ${op(i.op[1])}}, ${i.fb}, ${i.con}, ${i.pan}, ${i.ft || 0}, ${i.arpT || 0}, ${i.vibT || 0}, ${i.four ? 1 : 0}, ${i.fmm && i.fmm.len ? '&' + P + 'FM' + k : '0'}},`));
  o.push('};');
  o.push(`static const uint8_t ${P}ORDER[${s.order.length}] = {${s.order.join(', ')}};`);
  /* the patterns: present ones only */
  const rowIx = [], cells = [];
  const npat = s.patterns.length;
  for (let p = 0; p < npat; p++) {
    const Q = s.patterns[p];
    if (!Q) { rowIx.push(null); continue; }
    const ix = [];
    for (let r = 0; r < s.rows; r++) { ix.push(cells.length);
      for (let c = 0; c < 20; c++) { const L = Q[r][c]; if (L[0] === -1 && !L[1] && L[2] < 0 && L[4] < 0) continue; cells.push([c, ...L]); } }
    ix.push(cells.length); rowIx.push(ix);
  }
  ncells += cells.length;
  o.push(`static const PCell ${P}CELLS[${cells.length || 1}] = {${cells.map(c => `{${c[0]}, {${c[1]}, ${c[2]}, {${c[3]}, ${c[5]}}, {${c[4] & 255}, ${c[6] & 255}}}}`).join(',\n    ') || '{0}'}};`);
  rowIx.forEach((ix, p) => { if (ix) o.push(`static const uint16_t ${P}ROW${p}[${ix.length}] = {${ix.join(', ')}};`); });
  o.push(`static const uint16_t *const ${P}ROWS[${npat || 1}] = {${rowIx.map((ix, p) => ix ? P + 'ROW' + p : '0').join(', ') || '0'}};`);
  const tab = t => `{${t.len}, ${t.spd}, ${t.delay | 0}, ${t.loop}, {${t.data.map(v => v | 0).join(', ')}}}`;
  o.push(`static const EngTab ${P}ARP[16] = {${s.arp.map(tab).join(',\n    ')}};`);
  o.push(`static const EngTab ${P}VIB[16] = {${s.vib.map(tab).join(',\n    ')}};`);
  const names = (k, a) => o.push(`static const char *const ${P}${k}[${a.length || 1}] = {${a.map(x => JSON.stringify((x || '').toUpperCase().slice(0, 11))).join(', ') || '0'}};`);
  names('INAME', s.inst.map(i => i.name)); names('ANAME', s.arp.map(t => t.name)); names('VNAME', s.vib.map(t => t.name));
  o.push(`static const PSong ${P}SONG = {${JSON.stringify((s.name || songs[n].name).toUpperCase().slice(0, 20))}, ${P}CELLS, ${P}ROWS, ${npat}, {${s.rows}, ${s.bpm}, ${s.speed}, ${s.lfo || 0}, ${s.opl}, ${s.perc ? 1 : 0}, ${s.four || 0}, ${s.gvol}, ${s.vtab || 0}, ${s.mspd || 1}, ${s.order.length}, ${P}ORDER, ${s.inst.length}, ${P}INST}, ${P}ARP, ${P}VIB, ${P}INAME, ${P}ANAME, ${P}VNAME};`);
});
o.push(`#define NSONGS ${songs.length}`);
o.push(`static const PSong *const SONGS[NSONGS] = {${songs.map((_, n) => '&S' + n + '_SONG').join(', ')}};`);
process.stdout.write(o.join('\n') + '\n');
process.stderr.write(`${songs.length} songs, ${ncells} cells\n`);
